// Generates ar/index.html (the Arabic, right-to-left page) from index.html.
//
//   node build-ar.mjs            build ar/index.html
//   node build-ar.mjs --missing  list English strings that have no translation yet
//
// How it works: every piece of visible English text in <body> (and the
// placeholder / aria-label / title / alt attributes) is looked up in
// ar-dict.mjs, keyed by the exact English source (whitespace collapsed).
// If you change English copy in index.html the old key no longer matches,
// so the build stops and lists the strings that need a new Arabic version.
// Text without Latin letters (numbers, times, Arabic) is copied unchanged.
// Strings generated by the page script live in the STR table in index.html.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { HEAD, TEXT } from './ar-dict.mjs';

const listOnly = process.argv.includes('--missing');
let html = readFileSync(new URL('./index.html', import.meta.url), 'utf8');
const missing = new Set();
const used = new Set();

// 1. exact head / structural swaps (each must match exactly once)
for (const [en, ar] of HEAD) {
  const n = html.split(en).length - 1;
  if (n !== 1) throw new Error(`HEAD swap matched ${n}× (expected 1):\n  ${en}`);
  html = html.replace(en, () => ar);
}

// 2. body text + attributes
const norm = t => t.replace(/\s+/g, ' ').trim();
const latin = /[A-Za-z]/;
function tr(raw) {
  const key = norm(raw);
  if (!key || !latin.test(key)) return raw;
  if (!(key in TEXT)) { missing.add(key); return raw; }
  used.add(key);
  const lead = raw.match(/^\s*/)[0], trail = raw.match(/\s*$/)[0];
  return lead + TEXT[key] + trail;
}
const bStart = html.indexOf('<body>');
const bEnd = html.lastIndexOf('<script>');
let body = html.slice(bStart, bEnd);
body = body.replace(/(<!--[\s\S]*?-->)|(<[^>]+>)|([^<]+)/g, (m, comment, tag, text) => {
  if (comment) return comment;
  if (tag) return tag.replace(/\s(placeholder|aria-label|title|alt)="([^"]*)"/g,
    (a, name, val) => ` ${name}="${tr(val)}"`);
  return tr(text);
});
html = html.slice(0, bStart) + body + html.slice(bEnd);

if (missing.size) {
  console.error(`${missing.size} untranslated string(s):`);
  for (const k of missing) console.error('  ' + JSON.stringify(k));
  if (!listOnly) process.exit(1);
}
if (listOnly) process.exit(0);
const unused = Object.keys(TEXT).filter(k => !used.has(k));
if (unused.length) console.warn(`note: ${unused.length} unused dictionary entr${unused.length === 1 ? 'y' : 'ies'}:\n  ` + unused.map(k => JSON.stringify(k)).join('\n  '));

html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- GENERATED by build-ar.mjs from index.html + ar-dict.mjs. Do not edit by hand. -->');
mkdirSync(new URL('./ar/', import.meta.url), { recursive: true });
writeFileSync(new URL('./ar/index.html', import.meta.url), html);
console.log('wrote ar/index.html');
